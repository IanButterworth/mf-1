// Writes dsp/dogs.inc from MF-1's own Woof sources, so the firmware cannot drift from the desktop app: each breed's
// names, colour, bark numbers and settings as bred. Built and run by tools/gen_dogs.sh.
#include <cstdio>

#include "internal.h"

static void str(const char* s) {
  putchar('"');
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') putchar('\\');
    putchar(*s);
  }
  putchar('"');
}

int main() {
  using namespace woof;
  const auto& all = breeds();
  printf("/* Generated by tools/gen_dogs.sh from MF-1's Sources/WoofCore. Do not edit. */\n\n");
  printf("#define WF_DOG_COUNT %d\n\n", (int)all.size());
  printf("static const wf_breed_t kBreeds[WF_DOG_COUNT] = {\n");
  for (const auto& b : all) {
    printf("  {");
    str(b.voiceName), printf(", "), str(b.breed), printf(", "), str(b.word), printf(", "), str(b.blurb);
    printf(",\n   0x%06X, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d,\n   ", b.accent, b.transpose, b.formant,
           b.rasp, b.throat, b.mouth, b.mouthLevel, b.breath, b.gruff, b.decay, b.start, b.rise, b.fall, b.mono ? 1 : 0,
           b.arpMode);
    const char* sep = "{";
    for (int i = 0; i < WF_FIELDS; i++, sep = ", ") printf("%s%d", sep, b.day[i]);
    printf("}},\n");
  }
  printf("};\n");
  return 0;
}
