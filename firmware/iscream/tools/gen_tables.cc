// Writes the firmware's generated tables from MF-1's own sources, so the firmware cannot drift from the
// desktop app: `gen fm` gives dsp/fm_tables.inc (the msfa lookup tables at the FM-1's 44.1 kHz) and
// `gen flavors` gives dsp/flavors.inc. Built and run by tools/gen_tables.sh.
#include <cmath>
#include <cstdio>
#include <cstring>

#include "dsp/fm_dsp.h"
#include "internal.h"

static const double kRate = 44100;

static void table(const char* name, const int32_t* v, int n) {
  printf("static const int32_t %s[%d] = {", name, n);
  for (int i = 0; i < n; i++) printf("%s%d", i == 0 ? "\n    " : i % 12 ? ", " : ",\n    ", v[i]);
  printf("\n};\n\n");
}

static void str(const char* s) {
  putchar('"');
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') putchar('\\');
    putchar(*s);
  }
  putchar('"');
}

static void fmTables() {
  mf1::Tables::init(kRate);
  table("kSinTab", mf1::Sin::tab, mf1::Sin::SAMPLES * 2);
  table("kExp2Tab", mf1::Exp2::tab, mf1::Exp2::SAMPLES * 2);

  // As msfa's freqlut, for this sample rate.
  int32_t freq[1025];
  double y = (double)(1LL << (24 + 20)) / kRate;
  double inc = std::pow(2, 1.0 / 1024);
  for (int i = 0; i < 1025; i++) {
    freq[i] = (int32_t)std::floor(y + 0.5);
    y *= inc;
  }
  table("kFreqTab", freq, 1025);

  int32_t fine[100];
  for (int f = 0; f < 100; f++) fine[f] = f ? (int32_t)std::floor(24204406.323123 * std::log(1 + 0.01 * f) + 0.5) : 0;
  table("kFineTab", fine, 100);

  printf("#define FM_LFO_UNIT %uu\n", (uint32_t)(mf1::N * 25190424 / kRate + 0.5));
  printf("#define FM_PITCHENV_UNIT %d\n", (int)(mf1::N * (1 << 24) / (21.3 * kRate) + 0.5));
}

static void flavorTable() {
  const auto& all = iscream::flavors();
  printf("#define ISC_FLAVOR_COUNT %d\n\n", (int)all.size());
  printf("static const isc_flavor_t kFlavors[ISC_FLAVOR_COUNT] = {\n");
  for (const auto& f : all) {
    uint8_t v[155];
    iscream::baseVoice(f, v);
    printf("  {");
    str(f.voiceName);
    printf(", ");
    str(f.title);
    printf(", ");
    str(f.blurb);
    printf(",\n   0x%06X, 0x%06X, 0x%06X, %d, %d, %d, %d,\n", f.color, f.accent, f.bits, f.pattern, f.mono ? 1 : 0,
           f.decays ? 1 : 0, f.baseSpread);
    const char* sep = "   {";
    for (int i = 0; i < 6; i++, sep = ", ") printf("%s%d", sep, f.op[i].det);
    sep = "}, {";
    for (int i = 0; i < 6; i++, sep = ", ") printf("%s%d", sep, f.op[i].spread);
    sep = "}, {";
    for (int i = 0; i < 6; i++, sep = ", ") printf("%s%d", sep, f.op[i].mod ? 1 : 0);
    sep = "},\n   {";
    for (int i = 0; i < IS_FIELDS; i++, sep = ", ") printf("%s%d", sep, f.sundae[i]);
    sep = "},\n   {";
    for (int i = 0; i < 155; i++, sep = i % 21 ? ", " : ",\n    ") printf("%s%d", sep, v[i]);
    printf("}},\n");
  }
  printf("};\n");
}

int main(int argc, char** argv) {
  bool flavors = argc > 1 && !strcmp(argv[1], "flavors");
  printf("/* Generated by tools/gen_tables.sh from MF-1's %s. Do not edit. */\n\n",
         flavors ? "Sources/IScreamCore" : "Sources/MF1Core/dsp");
  if (flavors)
    flavorTable();
  else
    fmTables();
  return 0;
}
