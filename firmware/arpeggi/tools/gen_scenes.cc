// Writes dsp/scenes.inc from MF-1's own Arpeggi sources, so the firmware cannot drift from the desktop app: each
// scene's names, chord and settings as written, and each sound's operators. Built and run by tools/gen_scenes.sh.
#include <cstdio>

#include "internal.h"

static void str(const char* s) {
  putchar('"');
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') putchar('\\');
    putchar(*s);
  }
  putchar('"');
}

int main() {
  using namespace arpeggi;
  const auto& all = scenes();
  printf("/* Generated by tools/gen_scenes.sh from MF-1's Sources/ArpeggiCore. Do not edit. */\n\n");
  printf("#define AP_SCENE_COUNT %d\n\n", (int)all.size());
  printf("static const ap_scene_t kScenes[AP_SCENE_COUNT] = {\n");
  for (const auto& c : all) {
    printf("  {");
    str(c.voiceName), printf(", "), str(c.title), printf(", "), str(c.blurb);
    printf(",\n   %d, ", (int)c.seed.size());
    const char* sep = "{";
    for (int n : c.seed) printf("%s%d", sep, n), sep = ", ";
    printf("},\n   ");
    sep = "{";
    for (int i = 0; i < AP_FIELDS; i++, sep = ", ") printf("%s%d", sep, c.s[i]);
    printf("}},\n");
  }
  printf("};\n\n");
  printf("static const ap_sound_t kSounds[AP_SOUND_COUNT] = {\n");
  for (int i = 0; i < AP_SOUND_COUNT; i++) {
    const Sound& s = sound(i);
    printf("  {");
    str(s.name);
    printf(", %d, %d,\n   {", s.algorithm, s.feedback);
    for (int k = 0; k < 6; k++) {
      const Op& o = s.op[k];
      printf("%s{%d, %d, {%d, %d, %d, %d}, {%d, %d, %d, %d}, %d, %d, %d, %d}", k ? ",\n    " : "", o.ratio, o.level,
             o.r[0], o.r[1], o.r[2], o.r[3], o.l[0], o.l[1], o.l[2], o.l[3], o.bright ? 1 : 0, o.detune, o.rateScale,
             o.ams);
    }
    printf("},\n   %d, %d, %d, %d, %d, %d, %d, %d, %d, %d},\n", s.transpose, s.lfoSpeed, s.lfoDelay, s.pmd, s.amd,
           s.lfoWave, s.pms, s.lfoSync ? 1 : 0, s.roomType, s.chorus);
  }
  printf("};\n");
  return 0;
}
