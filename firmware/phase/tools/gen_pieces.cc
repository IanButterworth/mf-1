// Writes dsp/pieces.inc from MF-1's own Phase sources, so the firmware cannot drift from the desktop app: each
// piece's names, cell and settings as written, and each sound's operators. Built and run by tools/gen_pieces.sh.
#include <cstdio>

#include "internal.h"

static void str(const char* s) {
  putchar('"');
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') putchar('\\');
    putchar(*s);
  }
  putchar('"');
}

int main() {
  using namespace phase;
  const auto& all = pieces();
  printf("/* Generated by tools/gen_pieces.sh from MF-1's Sources/PhaseCore. Do not edit. */\n\n");
  printf("#define PH_PIECE_COUNT %d\n\n", (int)all.size());
  printf("static const ph_piece_t kPieces[PH_PIECE_COUNT] = {\n");
  for (const auto& p : all) {
    printf("  {");
    str(p.voiceName), printf(", "), str(p.title), printf(", "), str(p.blurb);
    printf(",\n   %d, ", (int)p.cell.size());
    const char* sep = "{";
    for (int n : p.cell) printf("%s%d", sep, n), sep = ", ";
    printf("},\n   ");
    sep = "{";
    for (int i = 0; i < PH_FIELDS; i++, sep = ", ") printf("%s%d", sep, p.s[i]);
    printf("}},\n");
  }
  printf("};\n\n");
  printf("static const ph_sound_t kSounds[PH_SOUND_COUNT] = {\n");
  for (int i = 0; i < PH_SOUND_COUNT; i++) {
    const Sound& s = sound(i);
    printf("  {");
    str(s.name);
    printf(", %d, %d,\n   {", s.algorithm, s.feedback);
    for (int k = 0; k < 6; k++) {
      const Op& o = s.op[k];
      printf("%s{%d, %d, {%d, %d, %d, %d}, {%d, %d, %d, %d}, %d, %d, %d, %d}", k ? ",\n    " : "", o.ratio, o.level,
             o.r[0], o.r[1], o.r[2], o.r[3], o.l[0], o.l[1], o.l[2], o.l[3], o.bright ? 1 : 0, o.detune, o.rateScale,
             o.ams);
    }
    printf("},\n   %d, %d, %d, %d, %d, %d, %d, %d, %d},\n", s.transpose, s.lfoSpeed, s.lfoDelay, s.pmd, s.amd,
           s.lfoWave, s.pms, s.lfoSync ? 1 : 0, s.roomType);
  }
  printf("};\n");
  return 0;
}
