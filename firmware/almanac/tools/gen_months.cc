// Writes dsp/months.inc from MF-1's own Almanac sources, so the firmware cannot drift from the desktop app:
// each month's names, colours, chord, pattern and voice under a clear sky, and each sky's weather stack.
// Built and run by tools/gen_months.sh.
#include <cstdio>
#include <cstring>

#include "internal.h"

static void str(const char* s) {
  putchar('"');
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') putchar('\\');
    putchar(*s);
  }
  putchar('"');
}

static void bytes(const uint8_t* v, int n, int perLine) {
  const char* sep = "{";
  for (int i = 0; i < n; i++, sep = i % perLine ? ", " : ",\n    ") printf("%s%d", sep, v[i]);
  printf("}");
}

int main() {
  using namespace almanac;
  const auto& all = months();
  printf("/* Generated by tools/gen_months.sh from MF-1's Sources/AlmanacCore. Do not edit. */\n\n");
  printf("#define ALM_MONTH_COUNT %d\n\n", (int)all.size());
  printf("static const alm_month_t kMonths[ALM_MONTH_COUNT] = {\n");
  for (const auto& m : all) {
    uint8_t v[155];
    baseVoice(m, sky(AL_CLEAR), v);
    printf("  {");
    str(m.voiceName), printf(", "), str(m.month), printf(", "), str(m.title), printf(", "), str(m.blurb);
    printf(",\n   0x%06X, 0x%06X, 0x%06X, 0x%06X, 0x%06X, %d, %d, %d,\n   {", m.skyTop, m.skyBottom, m.ground, m.far,
           m.accent, m.season, m.mono ? 1 : 0, m.decays ? 1 : 0);
    for (int i = 0; i < 4; i++) printf("%s%d", i ? ", " : "", m.op[i].mod ? 1 : 0);
    printf("}, {");
    for (int i = 0; i < 5; i++) printf("%s%d", i ? ", " : "", m.chord[i]);
    printf("}, %d, %d, %d,\n   ", m.chordSize, m.arpMode, m.arpOctaves);
    const char* sep = "{";
    for (int i = 0; i < AL_FIELDS; i++, sep = ", ") printf("%s%d", sep, m.day[i]);
    printf("},\n   ");
    bytes(v, 155, 21);
    printf("},\n");
  }
  printf("};\n\n");
  printf("static const alm_sky_t kSkies[AL_SKY_COUNT] = {\n");
  for (int k = 0; k < AL_SKY_COUNT; k++) {
    const Sky& s = sky(k);
    uint8_t v[155];
    baseVoice(all[0], s, v);
    printf("  {");
    str(s.name);
    printf(", %d, %d, %d, %d, %d, %d, %d,\n   ", s.fb, s.lfoWave, s.lfoSlow, s.lfoFast, s.amd, s.quiet, s.loud);
    bytes(v, 42, 21);
    printf("},\n");
  }
  printf("};\n");
  return 0;
}
